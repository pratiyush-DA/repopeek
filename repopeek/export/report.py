"""Markdown Graph Report generator producing GRAPH_REPORT.md audit trail."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from repopeek.graph.analysis import find_import_cycles, god_nodes, suggest_questions, surprising_connections
from repopeek.graph.clustering import compute_cohesion_scores, detect_communities, generate_community_labels
from repopeek.models.schema import CanonicalGraph


def generate_graph_report(
    graph: CanonicalGraph,
    project_name: Optional[str] = None,
    communities: Optional[Dict[int, List[str]]] = None,
    cohesion_scores: Optional[Dict[int, float]] = None,
    community_labels: Optional[Dict[int, str]] = None,
    out_path: Optional[Path] = None,
) -> str:
    """Generate comprehensive GRAPH_REPORT.md audit report for human developers and AI agents."""
    p_name = project_name or "Repository"

    if communities is None:
        communities = detect_communities(graph)
    if cohesion_scores is None:
        cohesion_scores = compute_cohesion_scores(graph, communities)
    if community_labels is None:
        community_labels = generate_community_labels(graph, communities)

    gods = god_nodes(graph, top_n=10)
    surprises = surprising_connections(graph, communities=communities, top_n=8)
    cycles = find_import_cycles(graph)
    questions = suggest_questions(graph, communities=communities, top_n=7)

    # Compute language breakdown
    lang_files: Dict[str, set] = {}
    lang_nodes: Dict[str, int] = {}
    for nid, node in graph.nodes.items():
        lang = nid.split(":")[0] if ":" in nid else "other"
        lang_nodes[lang] = lang_nodes.get(lang, 0) + 1
        if node.span and node.span.file:
            lang_files.setdefault(lang, set()).add(node.span.file)

    total_files = len({n.span.file for n in graph.nodes.values() if n.span and n.span.file})
    total_nodes = len(graph.nodes)
    total_edges = len(graph.edges)

    date_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines: List[str] = []
    lines.append(f"# Knowledge Graph Audit Report — {p_name}")
    lines.append(f"> Generated by **RepoPeek Universal Intelligence Engine** on {date_str}.")
    lines.append("")

    # 1. Executive Summary
    lines.append("## Executive Summary")
    lines.append("")
    lines.append("| Metric | Value | Description |")
    lines.append("| :--- | :--- | :--- |")
    lines.append(f"| **Total Files** | {total_files} | Discovered and indexed source files |")
    lines.append(f"| **Code Entities (Nodes)** | {total_nodes} | Extracted classes, functions, files, configs |")
    lines.append(f"| **Relational Edges** | {total_edges} | Syntactic calls, definitions, imports, and bridges |")
    lines.append(f"| **Modular Communities** | {len(communities)} | Topologically partitioned functional clusters |")
    lines.append(f"| **Import Cycles** | {len(cycles)} | Circular dependency paths detected |")
    lines.append("")

    # Language breakdown
    lines.append("### Language Breakdown")
    lines.append("")
    lines.append("| Language | Files | Code Entities |")
    lines.append("| :--- | :--- | :--- |")
    for lang in sorted(lang_nodes.keys(), key=lambda l: lang_nodes[l], reverse=True):
        f_count = len(lang_files.get(lang, set()))
        n_count = lang_nodes[lang]
        lines.append(f"| `{lang}` | {f_count} | {n_count} |")
    lines.append("")

    # 2. Top God Nodes
    lines.append("## Top God Nodes (Architectural Hubs)")
    lines.append("Nodes with the highest degree centrality. These form the core abstractions but carry the highest blast radius.")
    lines.append("")
    if gods:
        lines.append("| Rank | Symbol | Kind | Total Degree | In | Out | File Citation |")
        lines.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
        for i, g in enumerate(gods, 1):
            lbl = g["label"]
            knd = g["kind"]
            deg = g["degree"]
            ind = g["in_degree"]
            outd = g["out_degree"]
            fl = g["file"]
            ln = g["start_line"]
            cite = f"`{fl}:{ln}`" if fl else "external"
            lines.append(f"| {i} | `{lbl}` | {knd} | **{deg}** | {ind} | {outd} | {cite} |")
    else:
        lines.append("*No significant god nodes detected.*")
    lines.append("")

    # 3. Modular Communities
    lines.append("## Modular Communities & Functional Clusters")
    lines.append("Unsupervised community clusters partitioned by topological affinity.")
    lines.append("")
    if communities:
        lines.append("| Cluster ID | Community Label | Size (Nodes) | Cohesion Score |")
        lines.append("| :--- | :--- | :--- | :--- |")
        for cid, member_ids in sorted(communities.items(), key=lambda x: len(x[1]), reverse=True):
            clabel = community_labels.get(cid, f"Cluster {cid}")
            cscore = cohesion_scores.get(cid, 0.0)
            score_bar = f"{cscore:.2f}"
            lines.append(f"| #{cid} | **{clabel}** | {len(member_ids)} | {score_bar} |")
    else:
        lines.append("*No community clusters detected.*")
    lines.append("")

    # 4. Surprising Connections
    lines.append("## Surprising & Cross-Boundary Connections")
    lines.append("Non-obvious relational couplings crossing directory, language, or community boundaries.")
    lines.append("")
    if surprises:
        lines.append("| Score | Source | Target | Relation | Rationale |")
        lines.append("| :--- | :--- | :--- | :--- | :--- |")
        for s in surprises:
            sc = s["score"]
            src = s["src_label"]
            dst = s["dst_label"]
            rel = s["type"]
            reasons = "; ".join(s["reasons"])
            lines.append(f"| **{sc}** | `{src}` | `{dst}` | {rel} | {reasons} |")
    else:
        lines.append("*No unexpected cross-boundary couplings detected.*")
    lines.append("")

    # 5. Import Cycles Audit
    lines.append("## Import & Dependency Cycles Audit")
    if cycles:
        lines.append(f"> [!WARNING] **{len(cycles)} Circular Dependency Chains Detected**")
        lines.append("")
        for idx, cycle in enumerate(cycles, 1):
            chain = " ➔ ".join(f"`{Path(p).name}`" for p in cycle)
            lines.append(f"{idx}. {chain}")
    else:
        lines.append("Zero circular dependencies detected. Dependency graph is clean and acyclic.")
    lines.append("")

    # 6. Suggested Architecture Questions
    lines.append("## Suggested Architectural Questions")
    lines.append("Automated exploratory prompts for developers and AI code assistants:")
    lines.append("")
    for q in questions:
        lines.append(f"- {q}")
    lines.append("")

    report_content = "\n".join(lines)

    if out_path:
        out_file = Path(out_path)
        out_file.parent.mkdir(parents=True, exist_ok=True)
        out_file.write_text(report_content, encoding="utf-8")

    return report_content
